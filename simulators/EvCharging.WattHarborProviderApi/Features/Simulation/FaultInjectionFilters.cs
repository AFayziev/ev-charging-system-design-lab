using EvCharging.WattHarborProviderApi.Features.Commands;
using EvCharging.WattHarborProviderApi.Features.Sessions;
using EvCharging.WattHarborProviderApi.Features.Telemetry;

namespace EvCharging.WattHarborProviderApi.Features.Simulation;

internal static class FaultInjectionFilters
{
    public static EndpointFilterDelegate ResponseLoss(
        EndpointFilterFactoryContext factory, EndpointFilterDelegate next)
    {
        var parameters = factory.MethodInfo.GetParameters();
        int stopIndex = Array.FindIndex(
            parameters,
            parameter => parameter.ParameterType == typeof(StopChargingRequest));
        if (stopIndex < 0 && !parameters.Any(parameter => parameter.ParameterType == typeof(StartChargingRequest)))
        {
            return next;
        }

        int correlationIndex = parameters.Single(parameter => parameter.ParameterType == typeof(Guid)).Position;
        var faults = factory.ApplicationServices.GetRequiredService<CommandFaults>();
        return async invocation =>
        {
            var result = await next(invocation);
            // A stop's operation key is generated by the caller, so it can also be targeted by its session.
            var fault = faults.Find(invocation.GetArgument<Guid>(correlationIndex))
                ?? (stopIndex < 0
                    ? null
                    : faults.Find(invocation.GetArgument<StopChargingRequest>(stopIndex).ExternalSessionId));
            if (fault is { LoseResponse: true })
            {
                // The handler commits the effect before returning; serialization has not started.
                invocation.HttpContext.Abort();
                return TypedResults.Empty;
            }

            return result;
        };
    }

    public static EndpointFilterDelegate SnapshotFailure(
        EndpointFilterFactoryContext factory, EndpointFilterDelegate next)
    {
        var parameters = factory.MethodInfo.GetParameters();
        if (!parameters.Any(parameter => parameter.ParameterType == typeof(GetSessionSnapshotQueryHandler)))
        {
            return next;
        }

        int sessionIndex = parameters.Single(parameter => parameter.ParameterType == typeof(Guid)).Position;
        var faults = factory.ApplicationServices.GetRequiredService<TelemetryFaults>();
        return invocation => faults.Find(invocation.GetArgument<Guid>(sessionIndex)) is { SnapshotUnavailable: true }
            ? ValueTask.FromResult<object?>(TypedResults.StatusCode(StatusCodes.Status503ServiceUnavailable))
            : next(invocation);
    }

    public static EndpointFilterDelegate LookupFailure(
        EndpointFilterFactoryContext factory, EndpointFilterDelegate next)
    {
        var parameters = factory.MethodInfo.GetParameters();
        bool lookup = parameters.Any(parameter =>
            parameter.ParameterType == typeof(GetCommandByExternalOperationIdQueryHandler)
            || parameter.ParameterType == typeof(GetSessionByExternalSessionIdQueryHandler)
            || parameter.ParameterType == typeof(GetSessionSnapshotQueryHandler));
        if (!lookup)
        {
            return next;
        }

        int correlationIndex = parameters.Single(parameter => parameter.ParameterType == typeof(Guid)).Position;
        var faults = factory.ApplicationServices.GetRequiredService<CommandFaults>();
        return invocation => faults.Find(invocation.GetArgument<Guid>(correlationIndex))?.LookupStatusCode is { } status
            ? ValueTask.FromResult<object?>(TypedResults.StatusCode(status))
            : next(invocation);
    }
}
